// =============================================================================
// axi_pkg
//
// Widths and encodings of the AXI4 bus between the caches, the crossbar and
// the AXI slaves (memories, UART, spare slots). axi_if takes its default
// widths from here, and axi_xbar uses the channel structs below to mux whole
// channels at once.
//
// Only the AXI4 signals WASP uses are modelled: no lock, cache, prot, qos,
// region or user.
// =============================================================================
package axi_pkg;

    parameter int AXI_ADDR_WIDTH = 32;
    parameter int AXI_DATA_WIDTH = 32;
    parameter int AXI_STRB_WIDTH = AXI_DATA_WIDTH / 8;
    parameter int AXI_ID_WIDTH   = 4;    // one width everywhere, passed through the crossbar

    typedef enum logic [1:0] {
        AXI_BURST_FIXED = 2'b00,
        AXI_BURST_INCR  = 2'b01,
        AXI_BURST_WRAP  = 2'b10
    } axi_burst_e;

    typedef enum logic [1:0] {
        AXI_RESP_OKAY   = 2'b00,
        AXI_RESP_EXOKAY = 2'b01,
        AXI_RESP_SLVERR = 2'b10,   // the slave refused the access (e.g. write to a read-only RAM)
        AXI_RESP_DECERR = 2'b11    // no slave at this address (generated by axi_xbar)
    } axi_resp_e;

    // AxSIZE of a full 32-bit beat; the only size the caches issue
    parameter logic [2:0] AXI_SIZE_WORD = 3'b010;

    // ---- channel payloads (everything except valid/ready) --------------------
    typedef struct packed {
        logic [AXI_ID_WIDTH-1:0]   id;
        logic [AXI_ADDR_WIDTH-1:0] addr;
        logic [7:0]                len;     // beats - 1
        logic [2:0]                size;
        logic [1:0]                burst;
    } axi_ax_t;                             // AW and AR

    typedef struct packed {
        logic [AXI_DATA_WIDTH-1:0] data;
        logic [AXI_STRB_WIDTH-1:0] strb;
        logic                      last;
    } axi_w_t;

    typedef struct packed {
        logic [AXI_ID_WIDTH-1:0]   id;
        logic [1:0]                resp;
    } axi_b_t;

    typedef struct packed {
        logic [AXI_ID_WIDTH-1:0]   id;
        logic [AXI_DATA_WIDTH-1:0] data;
        logic [1:0]                resp;
        logic                      last;
    } axi_r_t;

endpackage : axi_pkg

`default_nettype wire
